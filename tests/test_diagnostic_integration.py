"""Phase 6C: Real Compiler Error -> Diagnostic -> Mock AI Integration Testing.

Proves that real compiler errors generated by the actual lexer, parser, and semantic
analyzer flow seamlessly through the diagnostic infrastructure:
  Real Source
       ↓
  Real Lexer & Parser
       ↓
  Real Semantic Analyzer
       ↓
  Real Compiler Exception (ParseError, SemanticError)
       ↓
  DiagnosticErrorHandler & ContextExtractor
       ↓
  Structured Diagnostic
       ↓
  PromptBuilder
       ↓
  MockAIProvider
       ↓
  DiagnosticResponse
"""

import os
import sys

# Reconfigure stdout to UTF-8 for reliable arrow and symbol printing
if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

# Ensure workspace root is in sys.path
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from parser.parser import parse_source, ParseError
from semantics.semantic_analyzer import SemanticAnalyzer, SemanticError
from codegen.tac_generator import TACGenerator
from diagnostics.error_handler import DiagnosticErrorHandler, Diagnostic
from diagnostics.ai_diagnostic import (
    PromptBuilder,
    MockAIProvider,
    DiagnosticResponse,
    diagnose_with_provider,
)


def run_tests():
    print("=" * 60)
    print("PHASE 6C: REAL COMPILER -> DIAGNOSTIC INTEGRATION TEST")
    print("=" * 60)

    provider = MockAIProvider()
    builder = PromptBuilder()

    # --------------------------------------------------------------------------
    # TEST 1: Valid program
    # --------------------------------------------------------------------------
    print("\n--- TEST 1: Valid program ---")
    t1_src = (
        "x = 10\n"
        "y = x + 20\n"
    )
    handler1 = DiagnosticErrorHandler(default_filename="valid.pyl")

    # Real compilation pipeline
    ast1 = parse_source(t1_src)
    analyzer1 = SemanticAnalyzer()
    analyzer1.analyze(ast1)
    generator1 = TACGenerator()
    instructions1 = generator1.generate(ast1)
    tac_lines = [str(i) for i in instructions1]

    # Verify no diagnostics generated
    assert not handler1.has_errors(), "Valid program should produce zero diagnostics"
    assert "x = 10" in tac_lines, "Expected 'x = 10' in generated TAC"
    assert any("x + 20" in line for line in tac_lines), "Expected 'x + 20' in generated TAC"
    print("[PASS] Valid program completed without diagnostics.")

    # --------------------------------------------------------------------------
    # TEST 2: Undefined variable
    # --------------------------------------------------------------------------
    print("\n--- TEST 2: Undefined variable ---")
    t2_src = "x = y + 10\n"
    handler2 = DiagnosticErrorHandler(default_filename="undefined.pyl")

    caught_err2 = None
    try:
        ast2 = parse_source(t2_src)
        analyzer2 = SemanticAnalyzer()
        analyzer2.analyze(ast2)
    except SemanticError as e:
        caught_err2 = e

    assert caught_err2 is not None, "Expected SemanticError for undefined variable 'y'"
    diag2 = handler2.create_diagnostic(
        phase="semantic",
        message=caught_err2.message,
        line=caught_err2.line,
        column=caught_err2.column,
        filename="undefined.pyl",
        source=t2_src,
        exception=caught_err2,
    )
    handler2.add_diagnostic(diag2)

    assert diag2.phase == "semantic"
    assert diag2.error_type == "Semantic Error"
    assert "Undefined variable 'y'" in diag2.message
    assert diag2.line == 1
    assert diag2.column == 5
    assert "x = y + 10" in (diag2.context or "")
    assert "^" in (diag2.context or "")

    prompt2 = builder.build_prompt(diag2)
    resp2 = provider.diagnose(prompt2)
    assert isinstance(resp2, DiagnosticResponse)
    assert "defined" in resp2.explanation.lower()

    print("[PASS] Real SemanticError caught, structured, and routed to MockAIProvider.")
    print("\nFormatted Diagnostic:")
    print(handler2.format_diagnostic(diag2))
    print("\nMock AI Response:")
    print(resp2.format_response())

    # --------------------------------------------------------------------------
    # TEST 3: Type mismatch
    # --------------------------------------------------------------------------
    print("\n--- TEST 3: Type mismatch ---")
    t3_src = (
        "x = 10\n"
        'y = x + "hello"\n'
    )
    handler3 = DiagnosticErrorHandler(default_filename="type_mismatch.pyl")

    caught_err3 = None
    try:
        ast3 = parse_source(t3_src)
        analyzer3 = SemanticAnalyzer()
        analyzer3.analyze(ast3)
    except SemanticError as e:
        caught_err3 = e

    assert caught_err3 is not None, "Expected SemanticError for incompatible '+' operand types"
    diag3 = handler3.create_diagnostic(
        phase="semantic",
        message=caught_err3.message,
        line=caught_err3.line,
        column=caught_err3.column,
        filename="type_mismatch.pyl",
        source=t3_src,
        exception=caught_err3,
    )

    assert diag3.line == 2
    assert diag3.column == 7
    assert "int" in diag3.message and "str" in diag3.message
    assert diag3.context is not None

    resp3 = diagnose_with_provider(diag3, provider)
    assert isinstance(resp3, DiagnosticResponse)
    assert "incompatible" in resp3.explanation.lower()
    print("[PASS] Real type mismatch error caught and processed through diagnostic pipeline.")

    # --------------------------------------------------------------------------
    # TEST 4: Invalid boolean operation
    # --------------------------------------------------------------------------
    print("\n--- TEST 4: Invalid boolean operation ---")
    t4_src = (
        "x = 10\n"
        "y = 20\n"
        "z = x and y\n"
    )
    handler4 = DiagnosticErrorHandler(default_filename="bool_op.pyl")

    caught_err4 = None
    try:
        ast4 = parse_source(t4_src)
        analyzer4 = SemanticAnalyzer()
        analyzer4.analyze(ast4)
    except SemanticError as e:
        caught_err4 = e

    assert caught_err4 is not None, "Expected SemanticError for non-boolean operands to 'and'"
    diag4 = handler4.create_diagnostic(
        phase="semantic",
        message=caught_err4.message,
        line=caught_err4.line,
        column=caught_err4.column,
        filename="bool_op.pyl",
        source=t4_src,
        exception=caught_err4,
    )
    assert "boolean operator" in diag4.message.lower()

    resp4 = diagnose_with_provider(diag4, provider)
    assert "boolean" in resp4.explanation.lower()
    print("[PASS] Invalid boolean operation reached diagnostic pipeline and received targeted response.")

    # --------------------------------------------------------------------------
    # TEST 5: Invalid condition
    # --------------------------------------------------------------------------
    print("\n--- TEST 5: Invalid condition ---")
    t5_src = (
        "x = 10\n"
        "if x:\n"
        "    y = 20\n"
    )
    handler5 = DiagnosticErrorHandler(default_filename="condition.pyl")

    caught_err5 = None
    try:
        ast5 = parse_source(t5_src)
        analyzer5 = SemanticAnalyzer()
        analyzer5.analyze(ast5)
    except SemanticError as e:
        caught_err5 = e

    assert caught_err5 is not None, "Expected SemanticError for non-bool if condition"
    diag5 = handler5.create_diagnostic(
        phase="semantic",
        message=caught_err5.message,
        line=caught_err5.line,
        column=caught_err5.column,
        filename="condition.pyl",
        source=t5_src,
        exception=caught_err5,
    )
    assert "if condition must evaluate to 'bool'" in diag5.message.lower()

    resp5 = diagnose_with_provider(diag5, provider)
    assert "condition" in resp5.explanation.lower()
    print("[PASS] Non-boolean if condition verified and diagnostic generated.")

    # --------------------------------------------------------------------------
    # TEST 6: Syntax error
    # --------------------------------------------------------------------------
    print("\n--- TEST 6: Syntax error ---")
    t6_src = (
        "if x > 5\n"
        "    y = 10\n"
    )
    handler6 = DiagnosticErrorHandler(default_filename="syntax.pyl")

    caught_err6 = None
    semantic_reached = False
    try:
        ast6 = parse_source(t6_src)
        semantic_reached = True
        analyzer6 = SemanticAnalyzer()
        analyzer6.analyze(ast6)
    except ParseError as e:
        caught_err6 = e

    assert not semantic_reached, "Semantic analyzer must not be reached when syntax error occurs"
    assert caught_err6 is not None, "Expected ParseError for missing colon after if"
    diag6 = handler6.create_diagnostic(
        phase="parser",
        message=caught_err6.message,
        line=caught_err6.line,
        column=caught_err6.column,
        filename="syntax.pyl",
        source=t6_src,
        exception=caught_err6,
    )
    assert diag6.phase == "parser"
    assert diag6.error_type == "Syntax Error"
    assert diag6.context is not None

    resp6 = diagnose_with_provider(diag6, provider)
    assert "syntax error" in resp6.explanation.lower()
    print("[PASS] Real parser syntax error halted compilation and produced structured diagnosis.")

    # --------------------------------------------------------------------------
    # TEST 7: Invalid indentation
    # --------------------------------------------------------------------------
    print("\n--- TEST 7: Invalid indentation ---")
    t7_src = (
        "if x > 5:\n"
        "x = 10\n"
    )
    handler7 = DiagnosticErrorHandler(default_filename="indent.pyl")

    caught_err7 = None
    semantic_reached_7 = False
    try:
        ast7 = parse_source(t7_src)
        semantic_reached_7 = True
        analyzer7 = SemanticAnalyzer()
        analyzer7.analyze(ast7)
    except ParseError as e:
        caught_err7 = e

    assert not semantic_reached_7, "Semantic analyzer must not be reached on indentation error"
    assert caught_err7 is not None, "Expected ParseError for missing indent"
    diag7 = handler7.create_diagnostic(
        phase="parser",
        message=caught_err7.message,
        line=caught_err7.line,
        column=caught_err7.column,
        filename="indent.pyl",
        source=t7_src,
        exception=caught_err7,
    )
    assert diag7.phase == "parser"
    assert diag7.context is not None
    print("[PASS] Indentation failure halted pipeline prior to semantic analysis and generated context.")

    # --------------------------------------------------------------------------
    # TEST 8: Multiple independent errors
    # --------------------------------------------------------------------------
    print("\n--- TEST 8: Multiple independent errors ---")
    shared_handler = DiagnosticErrorHandler(default_filename="multi_test.pyl")

    # Error A: Syntax error
    try:
        parse_source("if x > 5\n    y = 10\n")
    except ParseError as e:
        diag_a = shared_handler.create_diagnostic(
            phase="parser",
            message=e.message,
            line=e.line,
            column=e.column,
            filename="error_a.pyl",
        )
        shared_handler.add_diagnostic(diag_a)

    # Error B: Semantic error
    try:
        ast_b = parse_source("x = 10\ny = x + 'hi'\n")
        SemanticAnalyzer().analyze(ast_b)
    except SemanticError as e:
        diag_b = shared_handler.create_diagnostic(
            phase="semantic",
            message=e.message,
            line=e.line,
            column=e.column,
            filename="error_b.pyl",
        )
        shared_handler.add_diagnostic(diag_b)

    assert shared_handler.has_errors() is True
    all_errors = shared_handler.get_errors()
    assert len(all_errors) == 2, f"Expected 2 recorded errors, got {len(all_errors)}"
    assert all_errors[0].phase == "parser"
    assert all_errors[1].phase == "semantic"
    print(f"[PASS] Successfully collected {len(all_errors)} independent diagnostics across separate runs.")

    # --------------------------------------------------------------------------
    # TEST 9: Diagnostic prompt content
    # --------------------------------------------------------------------------
    print("\n--- TEST 9: Diagnostic prompt content ---")
    t9_src = "val = missing_name + 1\n"
    caught_err9 = None
    try:
        ast9 = parse_source(t9_src)
        SemanticAnalyzer().analyze(ast9)
    except SemanticError as e:
        caught_err9 = e

    assert caught_err9 is not None
    diag9 = handler2.create_diagnostic(
        phase="semantic",
        message=caught_err9.message,
        line=caught_err9.line,
        column=caught_err9.column,
        filename="missing.pyl",
        source=t9_src,
        exception=caught_err9,
    )
    prompt9 = builder.build_prompt(diag9)

    assert ".pyl" in prompt9, "Prompt missing .pyl reference"
    assert "SEMANTIC" in prompt9, "Prompt missing phase"
    assert "Undefined variable 'missing_name'" in prompt9, "Prompt missing error message"
    assert "missing.pyl" in prompt9, "Prompt missing filename"
    assert "Line: 1" in prompt9, "Prompt missing line coordinate"
    assert "val = missing_name + 1" in prompt9, "Prompt missing source context"
    assert "Supported Types: int, float, str, bool" in prompt9, "Prompt missing supported types"
    assert "Do not invent language features or compiler rules" in prompt9, "Prompt missing safety rule"
    print("[PASS] PromptBuilder output satisfies all language specification and context constraints.")

    # --------------------------------------------------------------------------
    # TEST 10: End-to-end real error demonstration
    # --------------------------------------------------------------------------
    print("\n--- TEST 10: End-to-end real error demonstration ---")
    t10_src = (
        "x = 10\n"
        'message = x + "items"\n'
    )

    caught_real_err = None
    try:
        # 1. Real lexer & parser
        ast10 = parse_source(t10_src)
        # 2. Real semantic analyzer
        SemanticAnalyzer().analyze(ast10)
    except SemanticError as e:
        caught_real_err = e

    assert caught_real_err is not None, "Real compiler error must be triggered"

    # 3. Create Diagnostic via DiagnosticErrorHandler
    diag10 = handler2.create_diagnostic(
        phase="semantic",
        message=caught_real_err.message,
        line=caught_real_err.line,
        column=caught_real_err.column,
        filename="shopping.pyl",
        source=t10_src,
        exception=caught_real_err,
    )

    # 4. Generate prompt via PromptBuilder
    prompt10 = builder.build_prompt(diag10)

    # 5. Receive mock response from MockAIProvider
    resp10 = provider.diagnose(prompt10)

    print("[PASS] Full end-to-end flow verified on real compiler error.")

    # Print requested demonstration outputs
    print("\n" + "=" * 60)
    print("END-TO-END DEMONSTRATION")
    print("=" * 60)

    print("\n1. ORIGINAL SOURCE:")
    print("-" * 60)
    print(t10_src.strip())

    print("\n2. COMPILER ERROR (RAW EXCEPTION):")
    print("-" * 60)
    print(f"Exception Type: {type(caught_real_err).__name__}")
    print(f"Message: {caught_real_err.message}")
    print(f"Location: Line {caught_real_err.line}, Column {caught_real_err.column}")

    print("\n3. STRUCTURED DIAGNOSTIC:")
    print("-" * 60)
    print(handler2.format_diagnostic(diag10))

    print("\n4. GENERATED PROMPT:")
    print("-" * 60)
    print(prompt10)

    print("\n5. MOCK AI RESPONSE:")
    print("-" * 60)
    print(resp10.format_response())

    # Final summary header and footer
    print("\n" + "=" * 60)
    print("PHASE 6C INTEGRATION TEST COMPLETE")
    print("=" * 60)
    print("ALL TESTS PASSED SUCCESSFULLY!\n")
    print("Pipeline verified:")
    print("REAL COMPILER ERROR")
    print("        ↓")
    print("Diagnostic")
    print("        ↓")
    print("Context")
    print("        ↓")
    print("Prompt")
    print("        ↓")
    print("Mock AI Response")


if __name__ == "__main__":
    run_tests()
