# ============================================================================
# Custom Parse Error Exception
# ============================================================================

class ParseError(Exception):
    """Custom exception raised on syntax errors during parsing."""

    def __init__(
        self,
        message: str,
        line: Optional[int] = None,
        column: Optional[int] = None,
        token: Optional[str] = None,
    ):
        super().__init__(message)
        self.message = message
        self.line = line
        self.column = column
        self.token = token


# ============================================================================
# Grammar Rules (CFG from GRAMMAR.md)
# ============================================================================

# --- Program & Statement List ---

def p_program_statements(p):
    """program : statement_list"""
    p[0] = ProgramNode(statements=p[1])


def p_program_empty(p):
    """program : empty"""
    p[0] = ProgramNode(statements=[])


def p_statement_list_multiple(p):
    """statement_list : statement_list statement"""
    p[0] = p[1] + [p[2]]


def p_statement_list_single(p):
    """statement_list : statement"""
    p[0] = [p[1]]


# --- Statements ---

def p_statement_simple(p):
    """statement : simple_statement"""
    p[0] = p[1]


def p_statement_compound(p):
    """statement : compound_statement"""
    p[0] = p[1]


def p_simple_statement(p):
    """simple_statement : assignment_statement"""
    p[0] = p[1]


def p_assignment_statement(p):
    """assignment_statement : IDENTIFIER ASSIGN expr NEWLINE"""
    col = getattr(p.slice[1], "column", None)
    target = IdentifierNode(name=p[1], lineno=p.lineno(1), column=col)
    p[0] = AssignmentNode(
        target=target,
        value=p[3],
        lineno=p.lineno(1),
        column=col,
    )


def p_compound_statement(p):
    """compound_statement : if_statement
                          | while_statement"""
    p[0] = p[1]


def p_block(p):
    """block : INDENT statement_list DEDENT"""
    col = getattr(p.slice[1], "column", None)
    p[0] = BlockNode(
        statements=p[2],
        lineno=p.lineno(1),
        column=col,
    )


# --- If / Elif / Else Statements ---

def p_if_statement(p):
    """if_statement : IF expr COLON NEWLINE block elif_list else_opt"""
    col = getattr(p.slice[1], "column", None)
    p[0] = IfNode(
        condition=p[2],
        then_block=p[5],
        elif_clauses=p[6],
        else_block=p[7],
        lineno=p.lineno(1),
        column=col,
    )


def p_elif_list_multiple(p):
    """elif_list : elif_list elif_clause"""
    p[0] = p[1] + [p[2]]


def p_elif_list_empty(p):
    """elif_list : empty"""
    p[0] = []


def p_elif_clause(p):
    """elif_clause : ELIF expr COLON NEWLINE block"""
    col = getattr(p.slice[1], "column", None)
    p[0] = ElifNode(
        condition=p[2],
        then_block=p[5],
        lineno=p.lineno(1),
        column=col,
    )


def p_else_opt_present(p):
    """else_opt : ELSE COLON NEWLINE block"""
    p[0] = p[4]


def p_else_opt_empty(p):
    """else_opt : empty"""
    p[0] = None


# --- While Loop ---

def p_while_statement(p):
    """while_statement : WHILE expr COLON NEWLINE block"""
    col = getattr(p.slice[1], "column", None)
    p[0] = WhileNode(
        condition=p[2],
        body=p[5],
        lineno=p.lineno(1),
        column=col,
    )


# --- Expressions & Precedence Hierarchy ---

# Level 1: Logical OR (Left-associative)
def p_expr_or(p):
    """expr : expr OR and_expr"""
    col = getattr(p.slice[2], "column", None)
    p[0] = BinaryOpNode(
        operator="or",
        left=p[1],
        right=p[3],
        lineno=p.lineno(2),
        column=col,
    )


def p_expr_passthrough(p):
    """expr : and_expr"""
    p[0] = p[1]


# Level 2: Logical AND (Left-associative)
def p_and_expr_and(p):
    """and_expr : and_expr AND not_expr"""
    col = getattr(p.slice[2], "column", None)
    p[0] = BinaryOpNode(
        operator="and",
        left=p[1],
        right=p[3],
        lineno=p.lineno(2),
        column=col,
    )


def p_and_expr_passthrough(p):
    """and_expr : not_expr"""
    p[0] = p[1]


# Level 3: Logical NOT (Unary prefix)
def p_not_expr_not(p):
    """not_expr : NOT not_expr"""
    col = getattr(p.slice[1], "column", None)
    p[0] = UnaryOpNode(
        operator="not",
        operand=p[2],
        lineno=p.lineno(1),
        column=col,
    )


def p_not_expr_passthrough(p):
    """not_expr : comparison"""
    p[0] = p[1]


# Level 4: Relational Comparisons (Non-associative binary)
def p_comparison_binop(p):
    """comparison : arith_expr comp_op arith_expr"""
    p[0] = BinaryOpNode(
        operator=p[2],
        left=p[1],
        right=p[3],
        lineno=p[1].lineno if hasattr(p[1], "lineno") else None,
        column=p[1].column if hasattr(p[1], "column") else None,
    )


def p_comparison_passthrough(p):
    """comparison : arith_expr"""
    p[0] = p[1]


def p_comp_op(p):
    """comp_op : LESS
               | GREATER
               | EQUALS
               | NOT_EQUALS"""
    p[0] = p[1]


# Level 5: Addition & Subtraction (Left-associative)
def p_arith_expr_binop(p):
    """arith_expr : arith_expr PLUS term
                  | arith_expr MINUS term"""
    col = getattr(p.slice[2], "column", None)
    p[0] = BinaryOpNode(
        operator=p[2],
        left=p[1],
        right=p[3],
        lineno=p.lineno(2),
        column=col,
    )


def p_arith_expr_passthrough(p):
    """arith_expr : term"""
    p[0] = p[1]


# Level 6: Multiplication & Division (Left-associative)
def p_term_binop(p):
    """term : term MULTIPLY factor
            | term DIVIDE factor"""
    col = getattr(p.slice[2], "column", None)
    p[0] = BinaryOpNode(
        operator=p[2],
        left=p[1],
        right=p[3],
        lineno=p.lineno(2),
        column=col,
    )


def p_term_passthrough(p):
    """term : factor"""
    p[0] = p[1]


# Level 7: Unary Arithmetic Negation (Prefix)
def p_factor_unary_minus(p):
    """factor : MINUS factor"""
    col = getattr(p.slice[1], "column", None)
    p[0] = UnaryOpNode(
        operator="-",
        operand=p[2],
        lineno=p.lineno(1),
        column=col,
    )


def p_factor_passthrough(p):
    """factor : primary"""
    p[0] = p[1]


# Level 8: Primaries, Grouping & Literals
def p_primary_identifier(p):
    """primary : IDENTIFIER"""
    col = getattr(p.slice[1], "column", None)
    p[0] = IdentifierNode(
        name=p[1],
        lineno=p.lineno(1),
        column=col,
    )


def p_primary_literal(p):
    """primary : literal"""
    p[0] = p[1]


def p_primary_paren(p):
    """primary : LPAREN expr RPAREN"""
    p[0] = p[2]


def p_literal(p):
    """literal : INT
               | FLOAT
               | STRING
               | BOOLEAN"""
    tok_type = p.slice[1].type
    type_map = {
        "INT": "int",
        "FLOAT": "float",
        "STRING": "str",
        "BOOLEAN": "bool",
    }
    col = getattr(p.slice[1], "column", None)
    p[0] = LiteralNode(
        value=p[1],
        type_name=type_map.get(tok_type, "unknown"),
        lineno=p.lineno(1),
        column=col,
    )


# --- Epsilon / Empty Production ---

def p_empty(p):
    """empty :"""
    pass


# ============================================================================
# Error Handling
# ============================================================================

def p_error(p):
    """Handle syntactic parsing errors."""
    if p:
        col = getattr(p, "column", None)
        col_str = f", Column {col}" if col is not None else ""
        msg = f"SyntaxError at line {p.lineno}{col_str}: Unexpected token '{p.value}' (type: {p.type})"
        raise ParseError(msg, line=p.lineno, column=col, token=str(p.value))
    else:
        msg = "SyntaxError: Unexpected end of input (EOF)"
        raise ParseError(msg, token="EOF")


# ============================================================================
# Parser Factory & Public API
# ============================================================================

_cached_parser = None


def build_parser(debug: bool = False, write_tables: bool = False, **kwargs):
    """Construct and return a PLY yacc parser instance."""
    global _cached_parser
    if _cached_parser is not None and not kwargs:
        return _cached_parser

    parser = yacc.yacc(
        debug=debug,
        write_tables=write_tables,
        **kwargs,
    )
    if not kwargs:
        _cached_parser = parser
    return parser


def parse_source(source: str, lexer=None, debug: bool = False) -> ProgramNode:
    """Parse source code string into an Abstract Syntax Tree (AST)."""
    parser = build_parser(debug=debug)
    if lexer is None:
        lexer = build_lexer()
    return parser.parse(source, lexer=lexer)


def parse_file(path: str, lexer=None, debug: bool = False) -> ProgramNode:
    """Read a .pyl source file and parse it into an AST."""
    with open(path, "r", encoding="utf-8") as f:
        source = f.read()
    return parse_source(source, lexer=lexer, debug=debug)


